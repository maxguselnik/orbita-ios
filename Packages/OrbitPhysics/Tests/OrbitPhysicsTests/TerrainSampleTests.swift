import Foundation
import Testing
@testable import OrbitPhysics

@Suite("Совместное семплирование рельефа")
struct TerrainSampleTests {
    @Test func lunarSamplePreservesExistingHeightsAndCraterColors() {
        // Значения из main до оптимизации; точки лежат на валу и вне кратеров.
        let fixtures: [(Vec3, Double, Double)] = [
            (Vec3(-0.8252778921954482, 0.18524289962473872, -0.5334805233483759), 652.0600768679278, 0.0),
            (Vec3(-0.5881696146349054, -0.3442988530472473, 0.7317887702134933), 537.6540697776163, 0.0),
            (Vec3(-0.6181729889819152, -0.37282125059778265, -0.6920017852548288), 1174.711731072489, 0.0),
            (Vec3(-0.47438787033141616, -0.3032726338017254, -0.826427164406754), 1374.3266257638634, 0.0),
            (Vec3(0.5643513765016819, -0.5236088973921476, 0.6382329092207926), 731.2236033554832, 0.0017900569542901458),
            (Vec3(-0.005691402343582645, 0.8452788975051369, 0.5342950433719778), 1210.048571616729, 0.0),
            (Vec3(0.46095591334430336, -0.618982791350921, 0.6359087591505099), 1207.3281136088256, 0.0),
            (Vec3(0.6464771651649951, -0.7121198855846133, 0.2737746216784691), 1868.3859411753674, 0.5387816970360533),
            (Vec3(0.6399632042851569, 0.6107919191428302, 0.46624063386934966), 1211.343101873638, 0.9495453407576565),
            (Vec3(0.6624939725543992, -0.5050899586913301, 0.5531598954717174), 90.28363755521815, 0.14724855678124346),
            (Vec3(-0.8022202473366945, -0.36024796842738943, 0.4760925078248883), 524.7828195748684, 0.0),
            (Vec3(0.7067476929206746, -0.0716978445979679, -0.7038232147573065), 1923.5405565583471, 0.0),
            (Vec3(-0.5398555962331414, -0.520742282727832, 0.6613496882853775), 1009.073191398446, 0.0),
            (Vec3(0.29949487288929555, -0.48450804152586874, -0.8219213945443882), 1849.9579174557098, 0.0),
            (Vec3(0.5125533681994987, -0.25998425734028385, -0.8183503104921328), 1541.1566482856963, 0.4052369872151627),
            (Vec3(0.4792084020095287, 0.8712686374814073, -0.10606728423395184), 738.9054363992022, 0.014011138835188185),
        ]
        for (direction, height, shade) in fixtures {
            let sample = Terrain.sample(body: .luna, direction: direction)
            #expect(abs(sample.height - height) < 1e-8)
            #expect(abs(sample.craterShade - shade) < 1e-10)
        }
    }

    @Test func terraSampleKeepsOceanFloorAndPadHeight() {
        let pad = Terrain.sample(body: .terra, direction: World.padDirection)
        #expect(abs(pad.height - Terrain.padHeight) < 1e-9)
        #expect(pad.craterShade == 0)
        // Земной рельеф не должен получать лунный оттенок кратеров.
        for direction in [Vec3.unitX, .unitY, .unitZ, -Vec3.unitX] {
            #expect(Terrain.sample(body: .terra, direction: direction).craterShade == 0)
        }
    }
}
